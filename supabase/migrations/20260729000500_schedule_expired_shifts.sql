-- ============================================================
-- Хугацаа өнгөрсөн зарыг автоматаар хаах хуваарь (FR-4.3)
-- ============================================================
-- Асуудал:
--   `close_expired_shifts()` функц бичигдсэн боловч түүнийг ХЭН Ч
--   дууддаггүй байсан. Тайлбарт нь "Supabase Dashboard → Cron дээр гараар
--   тохируулна" гэж бичсэн ч хийгдээгүй.
--
--   Үр дүнд нь өчигдрийн ээлж "Идэвхтэй" хэвээр жагсаалтад үлдэж, ажил
--   хайгч аль хэдийн өнгөрсөн ажилд хүсэлт илгээнэ. Зарын самбар хурдан
--   бохирдоно.
--
--   Мөн гараар тохируулсан хуваарь нь кодонд харагдахгүй тул төслийг өөр
--   орчинд сэргээхэд дагаж очихгүй.
--
-- Шийдэл:
--   pg_cron ашиглан 10 минут тутам ажиллуулна. Ингэснээр ээлж дуусаад
--   хамгийн ихдээ 10 минутын дотор хаагдана.
--
-- Яагаад өдөрт нэг удаа биш:
--   Ээлж нь цагийн нарийвчлалтай (жишээ нь өглөө 8-12 цаг). Өдөрт нэг
--   удаа хаавал өдрийн турш өнгөрсөн ээлж идэвхтэй харагдана.
--   UPDATE нь `status = 'Active' and end_at < now()` индекстэй тул хямд.
-- ============================================================

create extension if not exists pg_cron;

-- Дахин ажиллуулахад давхар хуваарь үүсэхээс сэргийлнэ
select cron.unschedule('close-expired-shifts')
where exists (select 1 from cron.job where jobname = 'close-expired-shifts');

select cron.schedule(
  'close-expired-shifts',
  '*/10 * * * *',
  $$ select public.close_expired_shifts() $$
);
