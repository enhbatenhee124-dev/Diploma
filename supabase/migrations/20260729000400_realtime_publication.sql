-- ============================================================
-- Realtime-д ямар хүснэгт нэвтрэхийг тодорхойлно
-- ============================================================
-- Supabase Realtime нь `supabase_realtime` publication-д БҮРТГЭГДСЭН
-- хүснэгтийн өөрчлөлтийг л түгээдэг. Өмнө нь үүнийг Supabase-ийн
-- дашбоардаас ГАРААР тохируулж байсан бөгөөд энэ нь хоёр асуудалтай:
--
--   • Төслийг шинэ орчинд (жишээ нь шалгагчийн Supabase дээр) сэргээхэд
--     чат, мэдэгдэл чимээгүйхэн ажиллахаа болино — алдаа ч гарахгүй,
--     зүгээр л шинэ мессеж ирэхээ болино
--   • Тохиргоо кодонд харагдахгүй тул хэн ч мэдэхгүй
--
-- Тиймээс migration болгон бэхжүүлэв.
--
-- ⚠ Publication-д орсон нь өгөгдөл ил болно гэсэн үг БИШ — RLS хэвээр
--   хүчинтэй. Хэрэглэгч зөвхөн өөрийн харах эрхтэй мөрийн өөрчлөлтийг
--   хүлээж авна.
-- ============================================================

do $$
declare
  t text;
begin
  foreach t in array array['chat_messages', 'notifications']
  loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end;
$$;

-- `is_read` шинэчлэгдэхэд хуучин мөрийн утга дамжуулах шаардлагагүй тул
-- анхдагч (default) хэвээр үлдээнэ — сүлжээгээр илүү өгөгдөл явуулахгүй.
