-- ============================================================
-- Тэргүүлэгчдийн view-үүдийг definer горимд БЭХЖҮҮЛЭХ
-- ============================================================
-- Асуудал:
--   `20260727000400_gamification.sql` нь төгсгөлдөө гурван view-г
--   `security_invoker = on` болгодог. Гэтэл `20260731000100_invoker_views.sql`
--   нь тайлбартаа "rankings, user_progress, user_stats — бүх хэрэглэгчийн
--   дуусгасан ажлыг тоолох ёстой, RLS үүнийг нуудаг" гэж definer байх
--   ШААРДЛАГАТАЙ гэж бичсэн боловч БУЦААЖ тохируулаагүй.
--
--   Бодит өгөгдлийн сан definer хэвээр байна (хаа нэгтээ гараар засагдсан).
--   Өөрөөр хэлбэл код болон сан ЗӨРЖ байна.
--
-- Яагаад энэ аюултай вэ:
--   Төслийг ШИНЭ Supabase дээр migration-аар сэргээвэл эдгээр view нь
--   invoker болно. Тэр үед:
--
--     • `user_stats` нь `profiles`, `applications`, `shifts`-ээс уншдаг
--     • RLS нь ажилтанд ЗӨВХӨН өөрийн мөрийг харуулна
--       (хэмжсэн: ажилтан 15 профайлаас 1, 10 хүсэлтээс 4-ийг л хардаг)
--     • Тиймээс тэргүүлэгчдийн самбар дээр БУСАД бүх хүн 0 XP гарна
--
--   Алдаа ч шидэгдэхгүй, лог ч үлдэхгүй — зүгээр л чимээгүйхэн буруу тоо.
--   Яг ийм алдаа `20260729000700` (ажилтан хаагдсан зараа харахаа больсон)
--   дээр нэг удаа гарч байсан.
--
-- Аюулгүй байдал:
--   Эдгээр view нь БАГАНААРАА хамгаалагдсан — утас, и-мэйл, регистр, хаяг,
--   цалин огт ороогүй. Зөвхөн нэр, аватар, дуусгасан ажлын тоо, цаг,
--   үнэлгээний дундаж, EXP, түвшин. Энэ бол тэргүүлэгчдийн самбар нийтэд
--   аль хэдийн харуулдаг өгөгдөл.
--
--   Supabase Advisor нь "SECURITY DEFINER view"-г анхааруулга болгон
--   тэмдэглэнэ. Энэ нь ЗОРИУДЫНХ — `20260731000100` үүнийг тайлбарласан.
--
-- ⚠ Үнэлгээ нь ЭНД ОРООГҮЙ гэдгийг анхаар: `user_stats` доторх үнэлгээний
--   хэсэг мөн definer-ээр уншигдана. Хэрэв ирээдүйд FR-7.2 (үнэлгээ 7
--   хоног эсвэл хоёул өгтөл нуугдана) -ыг EXP-д тусгах шаардлага гарвал
--   тэр шүүлтийг view ДОТОР хийх ёстой — invoker болгож шийдэх гэвэл
--   дээрх 0 XP-ийн алдаа буцаж ирнэ.
-- ============================================================

alter view public.user_stats    set (security_invoker = off);
alter view public.user_progress set (security_invoker = off);
alter view public.rankings      set (security_invoker = off);
