-- ============================================================
-- Эмзэг view-үүдийг invoker горимд шилжүүлэх
-- ============================================================
-- Supabase Advisor нь `SECURITY DEFINER view`-г CRITICAL гэж тэмдэглэдэг:
-- тэдгээр нь ДУУДАГЧИЙН бус, ЭЗЭМШИГЧИЙН эрхээр ажилладаг тул RLS-ийг
-- тойрч болзошгүй.
--
-- Энэ төслийн 9 view-ээс 7 нь definer байх ЗАЙЛШГҮЙ шаардлагатай
-- (доор жагсаав). Харин ХАМГИЙН ЭМЗЭГ өгөгдөлтэй хоёр нь — нэхэмжлэл
-- болон баталгаажуулах дараалал — invoker горимд шилжиж чадна.
--
-- Яагаад одоо болж байна вэ:
--   `invoice_overview` анх `security_invoker = on` байсан. 20260728000100
--   миграцад `profiles`-ийн policy хатуурсны улмаас "админд ч хоосон
--   харагдана" гэж үзээд definer болгосон. Гэвч тэр үед нэмэгдсэн
--   `profiles_admin_all` policy нь админд БҮХ профайлыг уншуулдаг тул
--   JOIN нурахгүй. Хэмжилт үүнийг батлав:
--
--     profiles   админ 12/12 мөр уншина
--     invoices   ажил олгогч өөрийн 2, админ 2
--
--   Тиймээс invoker горимд буцаж болно.
--
-- Definer хэвээр үлдэх ЁСТОЙ 7:
--   public_shifts, public_employers  — зочин доод хүснэгтийг уншиж чадахгүй
--   public_profiles                  — ажилтан зөвхөн ӨӨРИЙН профайлыг уншина
--   rankings, user_progress, user_stats — бүх хэрэглэгчийн дуусгасан ажлыг
--                                        тоолох ёстой, RLS үүнийг нуудаг
--   visible_reviews                  — user_stats үүнээс уншдаг
--
--   Тэдгээр нь БАГАНААРАА хамгаалагдсан: утас, и-мэйл, регистр, хаяг
--   огт ороогүй. Advisor-ын анхааруулга үлдэнэ — энэ нь зориудын.
-- ============================================================

-- Мөрийн шүүлт нь view дотор хэвээр (`auth.uid()` / `is_admin()`).
-- Одоо RLS НЭМЖ давхар шалгана — хамгаалалт хоёр давхар болно.
alter view public.invoice_overview set (security_invoker = on);
alter view public.employer_queue   set (security_invoker = on);
