import { isNative } from '../config/runtime'

// ============================================================
// PWA — service worker бүртгэх
// ============================================================
// Утсанд "Нүүр дэлгэцэд нэмэх" боломжийг олгож, сүлжээгүй үед аппын
// бүрхүүлийг үзүүлнэ. iPhone дээр энэ бол native аппын ОРОЛЦОГЧ — Apple
// нь Mac болон $99-гүйгээр өөр зам өгдөггүй.
//
// ⚠ Capacitor аппад бүртгэхгүй: тэнд хуудас файлын системээс ачаалагддаг
//   тул кэшлэх давхарга илүүц бөгөөд аппын шинэчлэлтийг хуучин хувилбарт
//   тогтоох эрсдэлтэй.
//
// ⚠ Хөгжүүлэлтийн үед ч бүртгэхгүй: SW нь Vite-ийн hot reload-ыг кэшээр
//   дарж, "яагаад өөрчлөлт минь харагдахгүй байна аа" гэсэн будлианыг
//   үүсгэдэг.
// ============================================================

export function registerServiceWorker() {
  if (isNative) return
  if (!import.meta.env.PROD) return
  if (!('serviceWorker' in navigator)) return

  // `load`-ийг хүлээх нь эхний зурагдалтыг SW-ийн бүртгэлтэй өрсөлдүүлэхгүй
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch(err => {
      // Бүртгэл амжилтгүй болох нь апп ажиллахад саад биш — зүгээр л
      // offline боломж, суулгах санал алга болно
      console.warn('[pwa] service worker бүртгэгдсэнгүй:', err?.message || err)
    })
  })
}
